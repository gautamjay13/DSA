public class lowercase_concat {
    public static void main(String[] args) {
         String s = "Jay Gautam is 24 years old" ;
         System.out.println(s.toLowerCase());
          
         //concat - means joining of two strings 
         String a = "abc" ;
         String b= "xyz" ;
         System.out.println(a+b);
         System.out.println(a.concat(b));
    }
}
